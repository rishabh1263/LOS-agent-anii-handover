def test_a_photo_with_no_metadata_is_review_not_pass(photo, monkeypatch):
    """
    Half the real dataset has been through something that strips EXIF.

    That is not grounds to reject the evidence, and not grounds to accept it
    unseen either -- it goes to a human.
    """
    from app.agents.business_evidence import service

    monkeypatch.setattr(service, "read_overlay", lambda path: {})

    outcome = service.analyze_business_evidence(
        str(photo), "BUSINESS_PROOF_1", source_id="bp"
    )

    assert outcome.decision is Decision.REVIEW
    assert outcome.metadata_source is MetadataSource.NONE
    assert ReasonCode.GEOTAG_MISSING in outcome.reason_codes
    assert ReasonCode.METADATA_STRIPPED in outcome.reason_codes


