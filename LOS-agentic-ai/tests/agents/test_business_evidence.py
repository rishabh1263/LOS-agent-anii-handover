@pytest.mark.ocr
def test_real_business_photographs_when_the_dataset_is_present():
    """
    Runs only if real field-visit photos are dropped into the repository.

    Skipped by default: the production dataset is not committed here, and a
    synthetic pass must not be mistaken for validation against real evidence.
    """
    if not REAL_SAMPLES.is_dir():
        pytest.skip("real business proof samples not present")

    images = [
        p
        for p in sorted(REAL_SAMPLES.iterdir())
        if p.suffix.lower() in {".jpg", ".jpeg", ".png"}
    ]
    if not images:
        pytest.skip("no images in samples/business_proof")

    for image in images:
        outcome = analyze_business_evidence(
            str(image), "BUSINESS_PROOF_1", source_id=image.name
        )
        assert outcome.decision in (Decision.PASS, Decision.REVIEW, Decision.FAIL)
        assert outcome.business_existence_verified is False
