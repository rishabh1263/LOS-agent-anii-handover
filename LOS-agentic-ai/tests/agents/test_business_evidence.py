@pytest.mark.parametrize(
    "slot",
    [BusinessProofSlot.BUSINESS_PROOF_1, BusinessProofSlot.BUSINESS_PROOF_2],
)
def test_both_proof_slots_run_through_one_capability(geotagged, slot):
    """
    Proof 1 and Proof 2 are the same evidence class in two form slots.

    The slot is carried through as a label; it must not change how the
    evidence is judged, or the two slots have quietly become two agents.
    """
    outcome = analyze_business_evidence(str(geotagged), slot, source_id="bp")

    assert outcome.document_type is slot
    assert outcome.capability == "business_evidence"
    assert outcome.decision is Decision.PASS


def test_the_two_slots_reach_identical_verdicts_on_identical_evidence(geotagged):
    first = analyze_business_evidence(
        str(geotagged), BusinessProofSlot.BUSINESS_PROOF_1, source_id="bp"
    )
    second = analyze_business_evidence(
        str(geotagged), BusinessProofSlot.BUSINESS_PROOF_2, source_id="bp"
    )

    assert first.decision == second.decision
    assert first.checks == second.checks
    assert first.fields == second.fields


