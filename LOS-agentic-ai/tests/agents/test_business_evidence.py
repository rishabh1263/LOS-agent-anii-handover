def test_exif_gps_is_read_without_ocr(geotagged, monkeypatch):
    """
    The EXIF path must not touch OCR.

    A photo with intact metadata is the common case and has to stay cheap;
    if it silently fell through to OCR the latency budget would go with it.
    """
    from app.agents.business_evidence import service

    def explode(*args, **kwargs):
        raise AssertionError("EXIF path must not invoke overlay OCR")

    monkeypatch.setattr(service, "read_overlay", explode)

    outcome = service.analyze_business_evidence(
        str(geotagged), "BUSINESS_PROOF_1", source_id="bp"
    )

    assert outcome.metadata_source is MetadataSource.EXIF
    assert outcome.fields["latitude"] == pytest.approx(26.866553, abs=1e-4)
    assert outcome.fields["longitude"] == pytest.approx(84.643202, abs=1e-4)
    assert ReasonCode.GEOTAG_PRESENT in outcome.reason_codes


def test_southern_and_western_hemispheres_are_signed(tmp_path):
    # Pillow writes the synthetic EXIF; no extra dependency needed.
    path = with_exif_gps(
        synthetic_photo(tmp_path / "s.jpg"), latitude=-33.9, longitude=-70.6
    )

    data = read_exif(path)

    assert data["latitude"] < 0
    assert data["longitude"] < 0


