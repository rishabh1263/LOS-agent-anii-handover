def synthetic_photo(
    path: Path,
    size: tuple[int, int] = (1280, 960),
    *,
    detail: bool = True,
    dark: bool = False,
) -> Path:
    """
    A SYNTHETIC stand-in for a premises photograph.

    `detail` draws high-frequency structure so the blur measure has something
    to find; without it the image is a flat wash and reads as out of focus,
    which is how the blurred-input case is produced.
    """
    from PIL import Image, ImageDraw

    base = 30 if dark else 210
    image = Image.new("RGB", size, (base, base, base))
    draw = ImageDraw.Draw(image)

    if detail:
        step = 24
        ink = (10, 10, 10) if not dark else (90, 90, 90)
        for x in range(0, size[0], step):
            draw.line([(x, 0), (x, size[1])], fill=ink, width=3)
        for y in range(0, size[1], step):
            draw.line([(0, y), (size[0], y)], fill=ink, width=3)

    image.save(path, "JPEG", quality=92)
    return path


def with_exif_gps(
    path: Path,
    latitude: float = 26.866553,
    longitude: float = 84.643202,
    when: str = "2026:03:06 10:16:00",
    make: str = "SyntheticPhone",
) -> Path:
    """
    Write a SYNTHETIC EXIF GPS + timestamp header onto an image.

    Written with Pillow rather than a dedicated EXIF library so the test
    suite does not pull in a dependency that only fixtures would use.
    """
    from PIL import Image

    def to_dms(value: float) -> tuple[float, float, float]:
        value = abs(value)
        degrees = int(value)
        minutes_float = (value - degrees) * 60
        minutes = int(minutes_float)
        return (float(degrees), float(minutes), (minutes_float - minutes) * 60)

    with Image.open(path) as image:
        exif = image.getexif()
        exif[271] = make            # Make
        exif[272] = "Model-X"       # Model
        exif[306] = when            # DateTime

        gps = exif.get_ifd(0x8825)
        gps[1] = "N" if latitude >= 0 else "S"
        gps[2] = to_dms(latitude)
        gps[3] = "E" if longitude >= 0 else "W"
        gps[4] = to_dms(longitude)

        image.save(path, "JPEG", exif=exif, quality=92)

    return path


